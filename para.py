import json
import random

categories = ["Электроника", "Аксессуары","Книги","Игрушки","Одежда","Обувь","Спорт","Косметика"]

product_name = ["Наушники","Телефон","Планшет","Клавиатура","Мышь","Монитор","Колонка",
                "Чехол","Повербанк","Зарядка","Кабель","Сумка","Рюкзак","Журнал",
                "Чехов","Пушкин","Достоевский","Толстой","Ахматова","Лермонтов","Гоголь",
                "Погремушка","Медведь(лучше мужчины)","Кукла","Машинка","Наклейки","Конструктор","Раскраска",
                "Платье","Капюшон без худи","Изибриджи","Трусы с волком","Носки","Чулки","Костюм горничной(детский)",
                "Гучи тапки","Балениага","Абъебас","Нике","Говнодавы","Сандали(крутой872)","Чешки",
                "Футбольный мяч","Баскетбольный мяч","Волейбольный мяч","Теннисный мяч","Бандаж","Шест для стриптиза","Гриф",
                "Консилер","Тушь","Помада","Тени","Штукатурка","Румяна","Мейкапцелка"]

products = []
for i in range (1,1001):
    product = {
        "id": i, 
        "name": f"{random.choice(product_name)} {random.randint(1,100)} ",
        "price": round(random.uniform(500,50000),2),
        "rating": round(random.uniform(1.0,5.0),1),
        "categories": random.choice(categories),
        "in_stock": random.choice([True,False])
    }
    products.append(product)
with open("products.json","w",encoding="utf-8") as f:
    json.dump(products,f,ensure_ascii=False,indent=4)
print("Файл готов, количество товаров:",len(products))

